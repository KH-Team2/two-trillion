-- ▶ TRG_DEDUCTION_TYPE_HISTORY: DEDUCTION_TYPE를 UPDATE 하면 바뀐 칸마다 CRITERIA_HISTORY 1행 (v4.4 · D-13)
CREATE OR REPLACE TRIGGER TRG_DEDUCTION_TYPE_HISTORY
AFTER UPDATE ON DEDUCTION_TYPE
FOR EACH ROW
DECLARE
  v_id   NUMBER := :OLD.TYPE_ID;
  v_year NUMBER := :OLD.TAX_YEAR;
  v_by   NUMBER := NULL;
  -- 값이 달라졌을 때만 남김 (NULL은 = · <> 로 비교가 안 돼서 비어 있던 칸에 값을 넣거나 비우는 경우를 따로 확인 · DECODE는 PL/SQL에서 못 씀 PLS-00204)
  PROCEDURE log_change(p_col VARCHAR2, p_old VARCHAR2, p_new VARCHAR2) IS
  BEGIN
    IF p_old <> p_new OR (p_old IS NULL AND p_new IS NOT NULL) OR (p_old IS NOT NULL AND p_new IS NULL) THEN
      INSERT INTO CRITERIA_HISTORY (HISTORY_ID, TABLE_NAME, TARGET_ID, TAX_YEAR, COLUMN_NAME, OLD_VALUE, NEW_VALUE, CHANGED_BY)
      VALUES (SEQ_CRITERIA_HISTORY.NEXTVAL, 'DEDUCTION_TYPE', v_id, v_year, p_col, SUBSTRB(p_old, 1, 200), SUBSTRB(p_new, 1, 200), v_by);
    END IF;
  END;
BEGIN
  -- 바꾼 관리자: 이번 UPDATE에 UPDATED_BY를 같이 넣었을 때만 (안 넣으면 예전 수정자가 남아 있어서 그 값을 쓰면 틀림)
  IF UPDATING('UPDATED_BY') THEN
    v_by := :NEW.UPDATED_BY;
  END IF;
  log_change('TAX_YEAR', TO_CHAR(:OLD.TAX_YEAR), TO_CHAR(:NEW.TAX_YEAR));
  log_change('TYPE_CODE', :OLD.TYPE_CODE, :NEW.TYPE_CODE);
  log_change('TYPE_NAME', :OLD.TYPE_NAME, :NEW.TYPE_NAME);
  log_change('DEDUCTION_KIND', :OLD.DEDUCTION_KIND, :NEW.DEDUCTION_KIND);
  log_change('RATE', TO_CHAR(:OLD.RATE), TO_CHAR(:NEW.RATE));
  log_change('LIMIT_AMOUNT', TO_CHAR(:OLD.LIMIT_AMOUNT), TO_CHAR(:NEW.LIMIT_AMOUNT));
  log_change('SALARY_MIN', TO_CHAR(:OLD.SALARY_MIN), TO_CHAR(:NEW.SALARY_MIN));
  log_change('SALARY_MAX', TO_CHAR(:OLD.SALARY_MAX), TO_CHAR(:NEW.SALARY_MAX));
  log_change('CATEGORY_ID', TO_CHAR(:OLD.CATEGORY_ID), TO_CHAR(:NEW.CATEGORY_ID));
  log_change('PAY_METHOD', :OLD.PAY_METHOD, :NEW.PAY_METHOD);
  log_change('SOURCE_NOTE', :OLD.SOURCE_NOTE, :NEW.SOURCE_NOTE);
END;
/

