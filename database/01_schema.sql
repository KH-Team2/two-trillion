-- ▶ CONSULT_MESSAGE: 관리자 상담 메시지 (v4.3)
--   메시지는 먼저 저장한 뒤 방 구독자에게 보냄 · 상대에게는 NOTIFICATION(NOTI_TYPE = 'CHAT') 알림
--   보낸 사람(SENDER_ID)은 백엔드가 로그인 토큰에서만 넣음 (화면이 보낸 senderId는 안 믿음) · 어느 관리자가 답했는지 여기 남음
--   내용은 1000자(글자 기준 · 한글도 1000자) · 주민번호 · 계좌번호 · 카드번호는 입력하지 말라고 화면에 안내
CREATE TABLE CONSULT_MESSAGE (
  MESSAGE_ID        NUMBER        NOT NULL,         -- 메시지번호 (지난 메시지 조회 beforeId 기준 · 순서 = MESSAGE_ID)
  ROOM_ID           NUMBER        NOT NULL,         -- 방번호 → CONSULT_ROOM
  SENDER_ID         NUMBER        NOT NULL,         -- 보낸 사람(회원 또는 관리자) → MEMBER
  CONTENT           VARCHAR2(1000 CHAR) NOT NULL,   -- 메시지 내용 (1000자)
  CREATED_AT        DATE          DEFAULT SYSDATE NOT NULL, -- 보낸 시각
  CONSTRAINT PK_CONSULT_MESSAGE PRIMARY KEY (MESSAGE_ID),
  CONSTRAINT FK_CONSULT_MESSAGE_ROOM FOREIGN KEY (ROOM_ID) REFERENCES CONSULT_ROOM (ROOM_ID) ON DELETE CASCADE,  -- 방 삭제 시 메시지도 삭제
  CONSTRAINT FK_CONSULT_MESSAGE_SENDER FOREIGN KEY (SENDER_ID) REFERENCES MEMBER (MEMBER_ID)
);

-- ▶ CRITERIA_HISTORY: 기준값 변경 이력 (v4.4 · 11/24 · D-13 · Jira TT-177)
--   세법 기준값 3개 테이블(DEDUCTION_TYPE · TAX_BRACKET · BENEFIT_CONDITION)은 연도별 한 행씩이라 관리자가 고치면 UPDATE로 덮어써서 이전 값이 안 남음
--   → 트리거(TRG_*_HISTORY)가 UPDATE 때마다 바뀐 칸 하나당 1행씩 이전 값 · 새 값을 자동으로 남김 (백엔드 · 계산 서버 · 기존 SQL은 그대로)
--   바꾼 관리자(CHANGED_BY)는 그 UPDATE에 같이 넣은 UPDATED_BY 값 · UPDATE에 UPDATED_BY가 없으면(스크립트로 직접 고침) NULL
--   INSERT · DELETE는 남기지 않음 (처음 값은 02_기준데이터.sql · 기준값 행은 지우지 않는 규칙)
--   대상 행(TARGET_ID)은 세 테이블 번호가 섞여서 FK 없음 · 이력은 지우지 않음 (97번 정리 대상 아님)
CREATE TABLE CRITERIA_HISTORY (
  HISTORY_ID        NUMBER        NOT NULL,         -- 이력번호
  TABLE_NAME        VARCHAR2(30)  NOT NULL,         -- 고친 테이블 DEDUCTION_TYPE/TAX_BRACKET/BENEFIT_CONDITION
  TARGET_ID         NUMBER        NOT NULL,         -- 고친 행 번호 (TYPE_ID · BRACKET_ID · BENEFIT_ID)
  TAX_YEAR          NUMBER(4)     NOT NULL,         -- 그 행의 적용 연도 (고치기 전 값)
  COLUMN_NAME       VARCHAR2(30)  NOT NULL,         -- 바뀐 칸 이름 (RATE · LIMIT_AMOUNT 등)
  OLD_VALUE         VARCHAR2(200),                  -- 이전 값 (글자로 · NULL = 비어 있었음)
  NEW_VALUE         VARCHAR2(200),                  -- 새 값 (글자로 · NULL = 비움)
  CHANGED_BY        NUMBER,                         -- 바꾼 관리자 → MEMBER (UPDATE의 UPDATED_BY · NULL = 스크립트로 고침)
  CHANGED_AT        DATE          DEFAULT SYSDATE NOT NULL, -- 바꾼 시각
  CONSTRAINT PK_CRITERIA_HISTORY PRIMARY KEY (HISTORY_ID),
  CONSTRAINT FK_CRITERIA_HISTORY_BY FOREIGN KEY (CHANGED_BY) REFERENCES MEMBER (MEMBER_ID),
  CONSTRAINT CK_CRITERIA_HISTORY_TABLE CHECK (TABLE_NAME IN ('DEDUCTION_TYPE', 'TAX_BRACKET', 'BENEFIT_CONDITION'))
);

